#!/usr/bin/env node

/**
 * CI Configuration Script for Agent Trainer
 *
 * This script generates wrangler.toml from environment variables for CI/CD deployments.
 *
 * Required environment variables:
 *   - AGENTS_KV_ID: The KV namespace ID for AGENTS_KV
 *   - TRAINING_JOBS_KV_ID: The KV namespace ID for TRAINING_JOBS_KV
 *
 * Optional environment variables:
 *   - AGENTS_KV_PREVIEW_ID: Preview namespace ID for AGENTS_KV (defaults to production ID)
 *   - TRAINING_JOBS_KV_PREVIEW_ID: Preview namespace ID for TRAINING_JOBS_KV (defaults to production ID)
 *   - HUGGINGFACE_API_URL: Custom HuggingFace API URL
 *   - WORKER_NAME: Custom worker name (defaults to 'agent-trainer')
 */

const fs = require('fs');
const path = require('path');

function generateWranglerConfig() {
  const agentsKvId = process.env.AGENTS_KV_ID;
  const trainingJobsKvId = process.env.TRAINING_JOBS_KV_ID;

  // Check for required environment variables
  if (!agentsKvId || !trainingJobsKvId) {
    console.error('\x1b[31mError: Missing required environment variables for CI deployment.\x1b[0m');
    console.error('');
    console.error('Required environment variables:');
    if (!agentsKvId) {
      console.error('  - AGENTS_KV_ID: not set');
    }
    if (!trainingJobsKvId) {
      console.error('  - TRAINING_JOBS_KV_ID: not set');
    }
    console.error('');
    console.error('To create KV namespaces and get their IDs:');
    console.error('  1. Run: wrangler kv:namespace create "AGENTS_KV"');
    console.error('  2. Run: wrangler kv:namespace create "TRAINING_JOBS_KV"');
    console.error('  3. Copy the namespace IDs from the output');
    console.error('  4. Set them as environment variables or Cloudflare Pages secrets');
    console.error('');
    console.error('Or run locally with: npm run setup');
    process.exit(1);
  }

  // Optional environment variables with defaults
  const agentsKvPreviewId = process.env.AGENTS_KV_PREVIEW_ID || agentsKvId;
  const trainingJobsKvPreviewId = process.env.TRAINING_JOBS_KV_PREVIEW_ID || trainingJobsKvId;
  const huggingfaceApiUrl = process.env.HUGGINGFACE_API_URL || 'https://api-inference.huggingface.co/models';
  const workerName = process.env.WORKER_NAME || 'agent-trainer';

  const wranglerConfig = `# Auto-generated wrangler.toml for CI/CD deployment
# Generated at: ${new Date().toISOString()}
#
# This file was generated by scripts/configure-wrangler.js
# Do not edit directly - modify environment variables instead

name = "${workerName}"
main = "src/index.js"
compatibility_date = "2024-08-01"

[[kv_namespaces]]
binding = "AGENTS_KV"
id = "${agentsKvId}"
preview_id = "${agentsKvPreviewId}"

[[kv_namespaces]]
binding = "TRAINING_JOBS_KV"
id = "${trainingJobsKvId}"
preview_id = "${trainingJobsKvPreviewId}"

# Environment variables
[vars]
HUGGINGFACE_API_URL = "${huggingfaceApiUrl}"

# Secrets (set with: wrangler secret put HUGGINGFACE_API_KEY)
# HUGGINGFACE_API_KEY = "your_api_key"
`;

  const wranglerPath = path.join(__dirname, '..', 'wrangler.toml');

  // Backup existing wrangler.toml if it exists and has real values
  if (fs.existsSync(wranglerPath)) {
    const existingContent = fs.readFileSync(wranglerPath, 'utf-8');
    if (!existingContent.includes('your_kv_namespace_id')) {
      const backupPath = path.join(__dirname, '..', 'wrangler.toml.backup');
      fs.writeFileSync(backupPath, existingContent);
      console.log(`Backed up existing wrangler.toml to wrangler.toml.backup`);
    }
  }

  fs.writeFileSync(wranglerPath, wranglerConfig);

  console.log('\x1b[32mwrangler.toml configured successfully for CI/CD deployment.\x1b[0m');
  console.log('');
  console.log('Configuration:');
  console.log(`  Worker name: ${workerName}`);
  console.log(`  AGENTS_KV ID: ${agentsKvId}`);
  console.log(`  AGENTS_KV Preview ID: ${agentsKvPreviewId}`);
  console.log(`  TRAINING_JOBS_KV ID: ${trainingJobsKvId}`);
  console.log(`  TRAINING_JOBS_KV Preview ID: ${trainingJobsKvPreviewId}`);
  console.log(`  HuggingFace API URL: ${huggingfaceApiUrl}`);
}

generateWranglerConfig();
